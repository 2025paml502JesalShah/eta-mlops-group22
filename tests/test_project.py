import os
import yaml
import pandas as pd


def test_params_yaml_exists():
    """Check that params.yaml exists."""
    assert os.path.exists("params.yaml")


def test_params_yaml_structure():
    """Check that params.yaml contains the expected configuration."""
    with open("params.yaml", "r", encoding="utf-8") as f:
        params = yaml.safe_load(f)

    assert "features" in params
    assert "model" in params

    assert "n_clusters" in params["features"]

    assert "test_size" in params["model"]
    assert "random_state" in params["model"]
    assert "outlier_threshold_seconds" in params["model"]
    assert "n_estimators" in params["model"]
    assert "max_depth" in params["model"]


def test_dvc_pipeline_exists():
    """Check that dvc.yaml exists and contains the expected stages."""
    assert os.path.exists("dvc.yaml")

    with open("dvc.yaml", "r", encoding="utf-8") as f:
        dvc_content = f.read()

    assert "build_features" in dvc_content
    assert "train_model" in dvc_content


def test_training_script_exists():
    """Check that the model training script exists."""
    assert os.path.exists("src/models/train_model.py")


def test_feature_engineering_script_exists():
    """Check that the feature engineering script exists."""
    assert os.path.exists("src/features/build_features.py")


def test_feature_dataset_configuration():
    """Check that the feature dataset is configured as a DVC pipeline output."""
    with open("dvc.yaml", "r", encoding="utf-8") as f:
        dvc_content = f.read()

    assert "data/features/nyc_features.csv" in dvc_content
    assert "src/features/build_features.py" in dvc_content

    # The feature dataset is generated by DVC, so it may not exist
    # in a clean GitHub Actions environment.
    # Only inspect it when it is available locally.
    path = "data/features/nyc_features.csv"

    if os.path.exists(path):
        df = pd.read_csv(path, nrows=10)

        assert len(df) > 0
        assert "haversine_km" in df.columns
        assert "pickup_cluster" in df.columns
        assert "dropoff_cluster" in df.columns


def test_model_configuration():
    """Check that the model output and metrics are configured in DVC."""
    with open("dvc.yaml", "r", encoding="utf-8") as f:
        dvc_content = f.read()

    assert "models/best_model.pkl" in dvc_content
    assert "reports/model_comparison.csv" in dvc_content
    assert "reports/normal_trip_model_comparison.csv" in dvc_content